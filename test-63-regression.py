from pathlib import Path
import re,subprocess,json
from html.parser import HTMLParser
p=Path(__file__).parent
class Inspect(HTMLParser):
 def __init__(self):super().__init__();self.ids=[];self.scripts=[]
 def handle_starttag(self,tag,attrs):
  a=dict(attrs)
  if a.get('id'):self.ids.append(a['id'])
  if tag=='script' and a.get('src'):self.scripts.append(a['src'].split('?')[0].removeprefix('./'))
for name in ['atlas.html','atlas-online.html','atlas-vi.html']:
 h=(p/name).read_text();r=Inspect();r.feed(h)
 assert len(r.ids)==len(set(r.ids)),name+' duplicate element IDs'
 assert all((p/s).exists() for s in r.scripts)
 for k in ('juraMapLegend','juraTrailerLegend','juraMapLegendRows','juraTrailerLegendRows','juraMapLegendSearch','juraTrailerSearch','juraNavCsv','juraNavPanel'): assert k in r.ids,(name,k)
 assert h.count('value="scaly,view"')==0, 'styles generated by javascript'
 assert 'atlas-dual-legends.js?v=65' in h and 'atlas.js?v=65' in h
s=(p/'atlas.js').read_text();options=s.split('const LAYERS=',1)[1].split('const VI_UV_OPTIONS=',1)[0]
assert options.count("['scaly,view'")==1 and options.count("['loki,view'")==1
j=(p/'atlas-dual-legends.js').read_text()
assert 'a.toggleLayer(' in j and 'a.toggleCategory(' in j and 'a.addRouteStop(' in j and 'a.selectPlace(' in j
n=(p/'atlas-navigation.js').read_text()
assert 'juraNavCsv' in n and 'Move stop' in n and 'juraNavExport' in n
assert 'Direct-line preview' in (p/'atlas-road-core.js').read_text()
assert 'shell66-research-workspace' in (p/'atlas-sw.js').read_text()
for f in p.glob('*.js'):
 z=subprocess.run(['node','--check',str(f)],capture_output=True,text=True)
 assert z.returncode==0,(f.name,z.stderr)
for f in p.rglob('*.json'): json.loads(f.read_text())
print('ATLAS 6.3 NEW REGRESSION: PASS — unique page IDs, referenced scripts, sole Scaly/Loki options, search/route actions, source scopes, valid JS/JSON, fresh shell.')
